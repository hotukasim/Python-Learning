x = 10 #assignment operator
print(x) #it will give 10 because we are printing the value of x
x = x + 5 #assignment operator
print(x) #it will give 15 because we are printing the value of x after adding 5 
x+= 5 #assignment operator
print(x) #it will give 20 because we are printing the value of x after adding 5 using shorthand operator
x-= 5 #assignment operator
print(x) #it will give 15 because we are printing the value of x after subtracting 5 using shorthand operator
x*= 5 #assignment operator
print(x) #it will give 75 because we are printing the value of x after multiplying 5 using shorthand operator
x/= 5 #assignment operator
print(x) #it will give 15.0 because we are printing the value of x after dividing 5 using shorthand operator
x//= 5 #assignment operator
print(x) #it will give 3.0 because we are printing the value of x after floor dividing 5 using shorthand operator
x%= 5 #assignment operator
print(x) #it will give 3.0 because we are printing the value of x after taking remainder of 5 using shorthand operator  
